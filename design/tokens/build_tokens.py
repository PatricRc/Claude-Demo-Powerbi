"""One palette, two engines.

Reads design/tokens/tokens.json and writes:
  design/tokens/tokens.css            CSS :root block for the HTML components
  design/theme/andinatech-theme.json  Power BI theme for the native visuals
  dax/_tokens.dax                     VAR block to paste at the top of each HTML measure

It also checks text contrast, so a token change cannot silently break legibility.

    python3 design/tokens/build_tokens.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
T = json.loads((ROOT / "design/tokens/tokens.json").read_text(encoding="utf-8"))
C = T["color"]


def luminance(hex_color):
    rgb = [int(hex_color[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    lin = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in rgb]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]


def contrast(a, b):
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


# 1) CSS
css = [":root{"]
css += [f"  --{k}:{v};" for k, v in C.items()]
css += [f"  --font-display:{T['font']['display']};", f"  --font-ui:{T['font']['ui']};"]
css += [f"  --radius-{k}:{v};" for k, v in T["radius"].items()]
css += ["}"]
(ROOT / "design/tokens/tokens.css").write_text(
    "/* Generated by build_tokens.py from tokens.json. Do not edit by hand. */\n" + "\n".join(css) + "\n",
    encoding="utf-8")

# 2) Power BI theme
theme = {
    "name": T["name"],
    "dataColors": [C["accent"], C["accent-2"], C["accent-gold"], C["ink"], C["muted"], C["good"], C["bad"]],
    "foreground": C["ink"], "background": C["card"], "secondaryBackground": C["page"],
    "tableAccent": C["accent"], "good": C["good"], "bad": C["bad"], "neutral": C["muted"],
    "maximum": C["accent"], "minimum": C["warm"],
    "textClasses": {
        "title": {"fontFace": "Segoe UI Semibold", "color": C["ink"], "fontSize": 12},
        "label": {"fontFace": "Segoe UI", "color": C["sub"], "fontSize": 9},
        "callout": {"fontFace": "Segoe UI Light", "color": C["ink"], "fontSize": 28},
    },
    "visualStyles": {
        "*": {"*": {
            "title": [{"show": False}],
            "border": [{"show": False}],
            "background": [{"show": False}],
            "dropShadow": [{"show": False}],
            "padding": [{"top": 0, "left": 0, "right": 0, "bottom": 0}],
            "valueAxis": [{"fontSize": 9, "gridlineShow": True,
                           "gridlineColor": {"solid": {"color": C["grid"]}}, "showAxisTitle": False}],
            "categoryAxis": [{"fontSize": 9, "showAxisTitle": False}],
        }},
        "page": {"*": {"background": [{"color": {"solid": {"color": C["page"]}}, "transparency": 0}]}},
        "slicer": {"*": {"items": [{"fontColor": {"solid": {"color": C["ink"]}}, "textSize": 10}]}},
    },
}
(ROOT / "design/theme").mkdir(parents=True, exist_ok=True)
(ROOT / "design/theme/andinatech-theme.json").write_text(json.dumps(theme, indent=2) + "\n", encoding="utf-8")

# 3) DAX token VARs (HTML Content does not share CSS between visuals, so every measure carries these)
dax_name = lambda k: "_" + "".join(p.capitalize() for p in k.split("-"))
dax = ["-- Generated by build_tokens.py from tokens.json. Paste at the top of each HTML measure."]
dax += [f'VAR {dax_name(k)} = "{v}"' for k, v in C.items()]
dax += [f'VAR _FontDisplay = "{T["font"]["display"]}"', f'VAR _FontUi = "{T["font"]["ui"]}"']
(ROOT / "dax").mkdir(exist_ok=True)
(ROOT / "dax/_tokens.dax").write_text("\n".join(dax) + "\n", encoding="utf-8")

# 4) Contrast check (body text 4.5:1, large numbers 3:1)
pairs = [("ink", "card", 4.5), ("sub", "card", 4.5), ("muted", "card", 4.5), ("accent", "card", 4.5),
         ("good", "card", 4.5), ("bad", "card", 4.5), ("good", "good-bg", 4.5), ("bad", "bad-bg", 4.5),
         ("ink", "page", 4.5), ("card", "sidebar", 4.5)]
failed = 0
for fg, bg, need in pairs:
    r = contrast(C[fg], C[bg])
    failed += r < need
    print(f"{'PASS' if r >= need else 'FAIL'}  {fg:<11} on {bg:<8} {r:5.2f}:1 (need {need})")
print("Wrote tokens.css, andinatech-theme.json, _tokens.dax")
raise SystemExit(1 if failed else 0)
